"""Compare Documents page. A functional page for Phase 5; Phase 6 replaces its layout."""

from __future__ import annotations

import pandas as pd
import streamlit as st

from core.document_comparator import (
    NOT_CORRECTNESS_NOTE,
    Comparison,
    ComparisonError,
    DocumentComparator,
    StatementDifference,
    TopicOverlap,
    UniquePassage,
)
from core.exporter import comparison_pdf, safe_filename
from database.db_manager import DatabaseManager
from database.schema import DocumentStatus
from ui import charts

_RESULT_KEY = "comparison_result"
_CHART_KEYWORDS = 12


def _percent(value: float | None) -> str:
    return "Not available" if value is None else f"{value * 100:.0f}%"


def _place(name: str, page: int | None) -> str:
    return f"{name}, p. {page}" if page else name


def _show_scores(comparison: Comparison) -> None:
    scores = comparison.scores
    columns = st.columns(4)
    columns[0].metric("Overall similarity", _percent(scores.overall))
    columns[1].metric(
        "Semantic",
        _percent(scores.semantic),
        help="Meaning: cosine similarity of passage embeddings, averaged in both directions.",
    )
    columns[2].metric(
        "Lexical", _percent(scores.lexical), help="Vocabulary: TF-IDF cosine similarity."
    )
    columns[3].metric(
        "Exact wording", _percent(scores.exact), help="Overlap of five-word sequences."
    )
    st.caption(NOT_CORRECTNESS_NOTE)


def _show_topics(title: str, topics: tuple[TopicOverlap, ...], keywords: list[str]) -> None:
    st.markdown(f"**{title}**")
    for topic in topics:
        st.markdown(f"- {topic.label}")
    if keywords:
        st.caption("Keywords: " + ", ".join(keywords[:_CHART_KEYWORDS]))
    elif not topics:
        st.caption("None found.")


def _show_difference(item: StatementDifference, comparison: Comparison) -> None:
    left, right = st.columns(2)
    left.markdown(f"**{_place(comparison.filename_a, item.page_a)}**")
    left.text(item.text_a)
    right.markdown(f"**{_place(comparison.filename_b, item.page_b)}**")
    right.text(item.text_b)
    changes = ", ".join(item.only_a) or "nothing"
    st.caption(f"{item.kind.value}: {changes} became {', '.join(item.only_b) or 'nothing'}")


def _show_unique(name: str, passages: tuple[UniquePassage, ...]) -> None:
    st.markdown(f"**Only in {name}**")
    if not passages:
        st.caption("No passages stand out as missing from the other document.")
    for passage in passages:
        st.text(passage.text)
        st.caption(f"{_place(name, passage.page)}, closest match {passage.best_score:.2f}")


def _show(comparison: Comparison) -> None:
    name_a, name_b = comparison.filename_a, comparison.filename_b
    _show_scores(comparison)
    for notice in comparison.notices:
        st.warning(notice)

    st.markdown("#### Summary")
    st.caption("Calculated from the results below. No AI model wrote this.")
    st.write(comparison.summary)
    if comparison.explanation:
        st.markdown("#### Explanation")
        st.caption(
            f"Generated by a local LLM ({comparison.explanation_model}). "
            "Check it against the calculated results."
        )
        st.write(comparison.explanation)

    st.markdown("#### Topics")
    columns = st.columns(3)
    with columns[0]:
        _show_topics("Common", comparison.common_topics, comparison.common_keywords)
    with columns[1]:
        _show_topics(
            f"Mainly in {name_a}", comparison.unique_topics_a, comparison.unique_keywords_a
        )
    with columns[2]:
        _show_topics(
            f"Mainly in {name_b}", comparison.unique_topics_b, comparison.unique_keywords_b
        )
    st.caption("Topic names are generated from important terms and are not reviewed labels.")

    st.markdown("#### Content differences")
    if not comparison.differences:
        st.caption("No matching statements with different content were found.")
    for item in comparison.differences:
        _show_difference(item, comparison)

    st.markdown("#### Information in one document only")
    left, right = st.columns(2)
    with left:
        _show_unique(name_a, comparison.unique_passages_a)
    with right:
        _show_unique(name_b, comparison.unique_passages_b)

    st.markdown("#### Similar passages")
    if not comparison.similar_passages:
        st.caption("No passages are similar enough to list.")
    for passage in comparison.similar_passages:
        left, right = st.columns(2)
        left.text(passage.text_a)
        left.caption(_place(name_a, passage.page_a))
        right.text(passage.text_b)
        right.caption(_place(name_b, passage.page_b))
        st.caption(f"{passage.kind.value}, similarity {passage.score:.2f}")

    st.markdown("#### Charts")
    keywords = comparison.keywords[:_CHART_KEYWORDS]
    if keywords:
        st.plotly_chart(charts.keyword_comparison(keywords, name_a, name_b))
        with st.expander("Keyword table"):
            st.dataframe(
                pd.DataFrame(
                    [
                        {"Keyword": k.term, name_a: round(k.score_a, 3), name_b: round(k.score_b, 3)}
                        for k in keywords
                    ]
                ),
                hide_index=True,
            )
    if comparison.grid:
        st.caption("Each cell shows the strongest passage match between two parts of the documents.")
        st.plotly_chart(charts.similarity_heatmap(comparison.grid, name_a, name_b))

    st.download_button(
        "Download report as PDF",
        comparison_pdf(comparison),
        file_name=f"{safe_filename(name_a)}-vs-{safe_filename(name_b)}.pdf",
        mime="application/pdf",
    )


def render(db: DatabaseManager, comparator: DocumentComparator, model: str | None) -> None:
    st.subheader("Compare two documents")
    documents = db.list_by_status(DocumentStatus.READY)
    if len(documents) < 2:
        st.caption("Upload at least two documents first.")
        return
    names = {doc.document_id: doc.original_filename for doc in documents}
    ids = list(names)
    left, right = st.columns(2)
    document_a = left.selectbox("Document A", ids, format_func=names.get)
    document_b = right.selectbox("Document B", ids, index=1, format_func=names.get)

    if st.button("Compare", type="primary"):
        try:
            with st.spinner("Comparing the documents"):
                st.session_state[_RESULT_KEY] = comparator.compare(document_a, document_b, model)
        except ComparisonError as exc:
            st.session_state.pop(_RESULT_KEY, None)
            st.error(str(exc))

    comparison = st.session_state.get(_RESULT_KEY)
    if comparison and (comparison.document_a, comparison.document_b) == (document_a, document_b):
        _show(comparison)
