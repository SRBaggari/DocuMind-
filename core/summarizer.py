"""Produce quick, detailed and executive summaries.

Summaries are sentences copied from the document, so they cannot invent facts.
Each Summary records how it was produced.
"""

from __future__ import annotations

import re
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from enum import StrEnum
from typing import Any

from config import Settings
from core.embedding_engine import ProgressCallback
from core.extractive import (
    GenerationMethod,
    Sentence,
    document_sentences,
    rank_sentences,
    select_diverse,
)
from core.indexing import read_content
from core.keyword_extractor import extract_keywords
from core.ollama_client import LocalLLM
from database.db_manager import DatabaseManager
from database.schema import DocumentStatus

NOT_STATED = "Not stated in the document."
_MAX_EXTRACTIVE_PARTS = 8

_PURPOSE = re.compile(
    r"\b(purpose|aims?|objectives?|goals?|examines?|this (report|study|paper|document|policy))\b",
    re.IGNORECASE,
)
_FINDING = re.compile(
    r"\b(found|findings?|results?|shows?|showed|increased?|decreased?|rose|fell|improved|"
    r"reduced?|declined?|reached)\b",
    re.IGNORECASE,
)
_CONCLUSION = re.compile(
    r"\b(conclu\w+|in summary|overall|therefore|expects?|future)\b", re.IGNORECASE
)
_ACTION = re.compile(r"\b(recommends?|should|must|needs? to|next steps?)\b", re.IGNORECASE)
_STATISTIC = re.compile(r"\d")

class SummaryMode(StrEnum):
    QUICK = "quick"
    DETAILED = "detailed"
    EXECUTIVE = "executive"


class SummaryError(Exception):
    """A summary cannot be produced. The message is safe to show to the user."""


@dataclass(frozen=True)
class SummarySection:
    title: str
    content: str


@dataclass(frozen=True)
class Summary:
    document_id: str
    filename: str
    mode: SummaryMode
    method: GenerationMethod
    model: str | None
    sections: tuple[SummarySection, ...]
    notices: tuple[str, ...] = ()

    @property
    def method_label(self) -> str:
        if self.method is GenerationMethod.LLM:
            return f"Generated by a local LLM ({self.model}). Check important details."
        return "Extractive summary: sentences copied from the document, not AI-written text."

    def to_markdown(self) -> str:
        lines = [f"# {self.filename}: {self.mode.value} summary", "", f"*{self.method_label}*", ""]
        for section in self.sections:
            lines += [f"## {section.title}", "", section.content, ""]
        lines += [f"> {notice}\n" for notice in self.notices]
        return "\n".join(lines).strip() + "\n"


def _cite(sentence: Sentence) -> str:
    return f"- {sentence.text} (p. {sentence.page_number})" if sentence.page_number else (
        f"- {sentence.text}"
    )


def _bullets(sentences: Sequence[Sentence]) -> str:
    return "\n".join(_cite(sentence) for sentence in sentences) or NOT_STATED


class Summarizer:
    def __init__(self, db: DatabaseManager, llm: LocalLLM, settings: Settings) -> None:
        self._db = db
        self._llm = llm
        self._settings = settings

    def summarize(
        self,
        document_id: str,
        mode: SummaryMode,
        model: str | None = None,
        use_llm: bool = True,
        progress: ProgressCallback | None = None,
    ) -> Summary:
        """Summarize a document, falling back to extractive if the LLM cannot be used."""
        document = self._db.get_document(document_id)
        if document is None or document.status is not DocumentStatus.READY:
            raise SummaryError("This document has no extracted text to summarize.")
        content = read_content(self._settings.paths, document_id)
        pages = [page for page in content["pages"] if page["text"]]

        sections = self._summarize_extractively(pages, content["blocks"], mode)
        return Summary(
            document_id,
            document.original_filename,
            mode,
            GenerationMethod.EXTRACTIVE,
            None,
            sections,
        )

    def _summarize_extractively(
        self,
        pages: list[dict[str, Any]],
        blocks: list[dict[str, Any]],
        mode: SummaryMode,
    ) -> tuple[SummarySection, ...]:
        sentences = document_sentences(pages)
        ranked = rank_sentences(sentences)
        if not ranked:
            raise SummaryError("This document has too little text to summarize.")

        def pick(pattern: re.Pattern[str] | None, limit: int) -> str:
            matching = [
                item for item in ranked if pattern is None or pattern.search(item[0].text)
            ]
            return _bullets(select_diverse(matching, limit, min_score=-1.0))

        if mode is SummaryMode.QUICK:
            return (
                SummarySection("Overview", pick(None, 3)),
                SummarySection("Main Purpose", pick(_PURPOSE, 1)),
                SummarySection("Important Findings", pick(_FINDING, 4)),
            )
        if mode is SummaryMode.EXECUTIVE:
            return (
                SummarySection("Document Purpose", pick(_PURPOSE, 2)),
                SummarySection("Main Findings", pick(_FINDING, 5)),
                SummarySection("Important Statistics", pick(_STATISTIC, 6)),
                SummarySection("Conclusions", pick(_CONCLUSION, 3)),
                SummarySection("Recommended Next Actions", pick(_ACTION, 3)),
            )

        keywords = extract_keywords([page["text"] for page in pages], 12)
        return (
            *self._section_summaries(pages, blocks),
            SummarySection(
                "Important Concepts", ", ".join(k.term for k in keywords) or NOT_STATED
            ),
            SummarySection("Supporting Information", pick(_STATISTIC, 6)),
            SummarySection("Conclusions", pick(_CONCLUSION, 3)),
        )

    def _section_summaries(
        self, pages: list[dict[str, Any]], blocks: list[dict[str, Any]]
    ) -> list[SummarySection]:
        parts = _heading_parts(blocks) or _page_parts(pages)
        sections = []
        for title, part_pages in parts:
            chosen = select_diverse(
                rank_sentences(document_sentences(part_pages)), 2, min_score=-1.0
            )
            if chosen:
                sections.append(SummarySection(title, _bullets(chosen)))
        return sections


def _heading_parts(blocks: Sequence[Mapping[str, Any]]) -> list[tuple[str, list[dict[str, Any]]]]:
    """Group DOCX blocks under their headings."""
    parts: list[tuple[str, list[str]]] = []
    for block in blocks:
        if block["kind"] == "heading" and block["level"]:
            parts.append((block["text"], []))
        elif parts and block["kind"] != "heading":
            parts[-1][1].append(block["text"])
    return [
        (title, [{"number": None, "text": "\n".join(body)}]) for title, body in parts if body
    ]


def _page_parts(pages: list[dict[str, Any]]) -> list[tuple[str, list[dict[str, Any]]]]:
    """Split a document without headings into a few even parts."""
    if len(pages) == 1 and pages[0]["number"] is None:
        paragraphs = [text for text in pages[0]["text"].split("\n\n") if text.strip()]
        pages = [{"number": None, "text": text} for text in paragraphs]
    size = max(-(-len(pages) // _MAX_EXTRACTIVE_PARTS), 1)
    parts = []
    for start in range(0, len(pages), size):
        group = pages[start : start + size]
        numbers = [page["number"] for page in group if page["number"]]
        if numbers:
            span = f"Page {numbers[0]}" if len(set(numbers)) == 1 else (
                f"Pages {numbers[0]}-{numbers[-1]}"
            )
        else:
            span = f"Part {len(parts) + 1}"
        parts.append((span, group))
    return parts
